/**
 * `pnpm --filter @bastion-mcp/api-client generate`: builds the OpenAPI 3.1 document from `packages/api`
 * (no infrastructure needed), writes it to `openapi.json` and regenerates `src/generated/schema.d.ts`.
 * Commit both. `pnpm --filter @bastion-mcp/api-client openapi:check` compares the document to the committed
 * `openapi.snapshot.json` and fails on breaking changes without a major version bump.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildOpenApiDocument } from '@bastion-mcp/api';
import openapiTS, { astToString, type OpenAPI3 } from 'openapi-typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const HEADER = `/**
 * Generated by \`pnpm --filter @bastion-mcp/api-client generate\` from the OpenAPI document of
 * \`@bastion-mcp/api\`. Do not edit by hand.
 */

`;

const main = async (): Promise<void> => {
  const doc = await buildOpenApiDocument();
  writeFileSync(resolve(root, 'openapi.json'), `${JSON.stringify(doc, null, 2)}\n`);
  const ast = await openapiTS(doc as OpenAPI3, { alphabetize: true });
  const out = resolve(root, 'src/generated/schema.d.ts');
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, HEADER + astToString(ast));
  console.log('wrote openapi.json and src/generated/schema.d.ts');
};

await main();
