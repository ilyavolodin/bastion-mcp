export type Collection = (typeof COLLECTIONS)[number];

/** The API representation of a stored resource; `updatedAt` (ISO 8601) is its ETag version. */
export type Row = { id: string; updatedAt: string } & Record<string, unknown>;

export type ListQuery = {
  limit: number;
  cursor?: string | undefined;
  /** Text search over the collection's searchable columns. */
  q?: string | undefined;
  /** `field` or `-field` already split. */
  sort?: { field: string; desc: boolean } | undefined;
  /** Equality filters on top-level fields. */
  where?: Record<string, unknown> | undefined;
};

export type Page<T> = { items: T[]; nextCursor: string | null };

export interface ResourceStore {
  list(collection: Collection, query: ListQuery): Promise<Page<Row>>;
  get(collection: Collection, id: string): Promise<Row | null>;
  /** All rows whose top-level fields equal `where` (unpaginated; for bounded lookups). */
  find(collection: Collection, where: Record<string, unknown>): Promise<Row[]>;
  /** `id` is generated by the store when absent. */
  insert(collection: Collection, data: Record<string, unknown> & { id?: string }): Promise<Row>;
  /** Shallow merge; bumps `updatedAt`. Throws `NotFoundApiError` when absent. */
  update(collection: Collection, id: string, patch: Record<string, unknown>): Promise<Row>;
  /** Replaces the row (insert when absent); bumps `updatedAt`. */
  upsert(collection: Collection, id: string, data: Record<string, unknown>): Promise<Row>;
  remove(collection: Collection, id: string): Promise<boolean>;
}
