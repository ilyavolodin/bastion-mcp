// Regenerates src/http/pages/fonts.generated.ts: the Poppins latin woff2 files (SIL OFL 1.1) embedded as base64 so
// the server-rendered pages self-host their font without a file lookup at runtime (CSP `font-src 'self'`).
// Run after bumping @fontsource/poppins: node apps/server/scripts/gen-fonts.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(join(here, '..', '..', 'web', 'package.json'));
const pkgDir = dirname(require.resolve('@fontsource/poppins/package.json'));
const weights = [400, 500, 600, 700];
const entries = weights.map((w) => {
  const file = readFileSync(join(pkgDir, 'files', `poppins-latin-${w}-normal.woff2`));
  return `  ${w}: '${file.toString('base64')}',`;
});
const out = `// Generated by scripts/gen-fonts.mjs from @fontsource/poppins (SIL Open Font License 1.1). Do not edit.
/** Poppins latin subset, woff2, base64, by weight. */
export const POPPINS_WOFF2_BASE64: Record<400 | 500 | 600 | 700, string> = {
${entries.join('\n')}
};
`;
writeFileSync(join(here, '..', 'src', 'http', 'pages', 'fonts.generated.ts'), out);
console.log('wrote fonts.generated.ts');
